def main_movies(
    source: Path,
    out_dir: Path,
    *,
    tsv_only: bool,
    tsv_path: Path,
    force: bool,
    only: list[str] | None,
) -> int:
    """The `boku movies` command body. Returns a process exit status."""
    try:
        if not source.is_file():
            raise MovieError(
                f"no image at {source}: run `./make.sh import` first. The repo ships none "
                f"of the game"
            )
        if tsv_only and only:
            raise MovieError(
                "--only names movies to decode, and --tsv decodes nothing; the table is "
                "always regenerated whole"
            )
        entries = parse_movie_ids(MOVIES_MD.read_text(encoding="utf-8"))
        with DiscImage(source) as image:
            on_disc = iki_entries(image)
            # The table is always the whole list: `--only` picks what to spend decode time
            # on, and a table holding only that would be a table of one movie.
            frames_by_file = {movie.name: movie.frames for movie in on_disc}
            if tsv_only:
                path = write_tsv(frames_by_file, tsv_path, entries=entries)
                print(f"{path}: {len(entries)} ids")
                return 0
            _decode_all(
                image,
                _wanted(on_disc, only),
                out_dir,
                entries=entries,
                force=force,
            )
            path = write_tsv(frames_by_file, tsv_path, entries=entries)
            print(f"{path} regenerated; fill in what_it_shows from watching them")
        return 0
    except (MovieError, DiscError) as refusal:
        print(f"boku movies: refused: {refusal}", file=sys.stderr)
        return 2


def _wanted(on_disc: list[MovieFile], only: list[str] | None) -> list[MovieFile]:
    if not only:
        return on_disc
    names = {name.upper() for name in only}
    chosen = [movie for movie in on_disc if movie.name.upper() in names]
    missing = names - {movie.name.upper() for movie in chosen}
    if missing:
        raise MovieError(f"no such movie on the image: {', '.join(sorted(missing))}")
    return chosen


def _decode_all(
    image: DiscImage,
    movies: list[MovieFile],
    out_dir: Path,
    *,
    entries: list[MovieId],
    force: bool,
) -> None:
    java = java_binary()
    jar = jpsxdec_jar()
    out_dir.mkdir(parents=True, exist_ok=True)
    by_file = ids_by_file(entries)
    total_size = 0
    total_time = 0.0
    done = 0
    # The scratch lives beside the output so that publishing a decoded movie is a rename
    # rather than a copy of up to 163 MB across filesystems.
    with tempfile.TemporaryDirectory(prefix=".boku-movies-", dir=out_dir) as scratch_name:
        for movie in movies:
            out_path = out_dir / f"{movie.name}.avi"
            if may_skip(out_path, movie, force=force):
                detail = "(already there)"
            else:
                result = decode_one(
                    image, movie, out_dir, java=java, jar=jar, scratch=Path(scratch_name)
                )
                done += 1
                total_size += result.size
                total_time += result.elapsed
                detail = f"({result.size / 1e6:.1f} MB, {result.elapsed:.1f}s)"
            ids = ",".join(str(i) for i in by_file.get(movie.name, [])) or "-"
            print(
                f"id {ids:<16} {movie.name:<6} {movie.frames:>5} frames "
                f"{movie.frames / FPS:>7.1f}s  {out_path}  {detail}"
            )
    print(
        f"\n{done} movie(s) decoded in {total_time:.1f}s, {total_size / 1e6:.1f} MB "
        f"written to {out_dir}/"
    )


def add_arguments(parser: argparse.ArgumentParser) -> argparse.ArgumentParser:
    parser.add_argument(
        "source",
        nargs="?",
        type=Path,
        default=DEFAULT_IMAGE,
        metavar="IMAGE",
        help=f"raw image to read (default: {DEFAULT_IMAGE.relative_to(REPO_ROOT)})",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT_DIR,
        metavar="DIR",
        help=f"where the movies go (default: {DEFAULT_OUT_DIR.relative_to(REPO_ROOT)}/)",
    )
    parser.add_argument(
        "--tsv",
        action="store_true",
        help=(
            f"only regenerate {MOVIES_TSV.relative_to(REPO_ROOT)} and stop -- no decoding, "
            f"so it needs neither Java nor jPSXdec"
        ),
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="decode a movie again even though its output is already there",
    )
    parser.add_argument(
        "--only",
        nargs="+",
        metavar="NAME",
        help="decode just these files, by name (M27, M010, ...)",
    )
    parser.set_defaults(
        run=lambda args: main_movies(
            args.source,
            args.out,
            tsv_only=args.tsv,
            tsv_path=MOVIES_TSV,
            force=args.force,
            only=args.only,
        )
    )
    return parser
