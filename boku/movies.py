"""The movies: slice each `__STR/*.IKI` off the import, decode it, and keep the list.

    ./make.sh movies            every movie into work/movies/<name>.avi, narration muxed in
    ./make.sh movies --tsv      just regenerate research/data/movies.tsv

An `.IKI` is real-time interleaved -- Form 1 video sectors and Form 2 XA audio sectors
alternate inside one extent by subheader channel -- so `boku import` does not extract it
(`boku.importer._is_cooked_file`) and 2048 bytes a sector is not its byte stream. What a
decoder needs is the extent's **raw** 2352-byte sectors, which is all `slice_movie` does.

Decoding is jPSXdec's job: ffmpeg demuxes an `.IKI` but its MDEC decoder rejects every IKI
frame, and it has no STR encoder either (`research/movies.md` § 4, which is the one home
for the install path and the flags). We ask for `-vf avi:mjpg -q psx -psxav` -- the same
decode `research/movies.md` § 4 names as the reference for timing -- and leave the XA
audio muxed in, because the narration is the point of watching these at all. AVI and not
mp4: this is jPSXdec's own one-step output, so the picture is compressed once rather than
twice, and VLC plays it as-is.

`research/data/movies.tsv` is the list, and it is generated rather than typed. The file's
own header says which column comes from where; `build_tsv` is where that is done.
"""

